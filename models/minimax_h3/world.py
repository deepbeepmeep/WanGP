"""pi-H3 worlds: a scene walked through segment after segment (model def "world_outputs" on a pi-H3 DWD model). Each segment is one
pi-H3 generation of a WINDOW_FRAMES window (history included) whose prompt is the world description and the sentence of the move (forward, backward, left,
right, an event); each one continues the previous one from its own output (model def "recycle_latents", MiniMaxH3Pipeline.
_recycled_overlap): the next segment's anchor (its first frame) is the frame opening the previous segment's tail clip, its history the
whole clips before it, its audio rows the previous segment's audio latents. pi-H3 DWD's final video latents are not clean latents (its
pixel head gives the frames from a still-noisy state), so its worlds declare recycle_latents "frames": the overlap rows are encoded once
from the frames the segment gave, nothing is decoded. A segment shows its frames up to the anchor: the next one regenerates the 4 after it.

A world is returned with its .wgpworld file (manifest, what the next segment reads of the last one, poster); given a world file,
generation continues it with the prompt's instructions, or serves its exploration (shared.utils.world_exploration) one segment per move
until the viewer leaves. The prompt encodings stay in the pipeline's TextEncoderCache: an exploration encodes the four moves and a still
camera once, at its start, and each new combination or event once, when first used."""
import io
import json
import math
import queue
import time
import uuid
import zipfile
from dataclasses import dataclass, field

import numpy as np
import torch
from PIL import Image
from safetensors.torch import load, save
from tqdm import tqdm

from shared.utils.phase_progress import check_abort, set_phase_status
from shared.utils.world_exploration import EXPLORE_PROMPT, exploration_for
from shared.utils.world_instructions import CONTROLS, split_instructions

FPS = 24
CLIP_FRAMES = 17  # an H3 VAE clip: 5 latents
WINDOW_FRAMES = 107  # frames of a segment's window, 5 + 17 * 6 (4.5 s), a continuing segment's history clips included: each segment
# costs the transformer what a 107-frame video does, and (anchor frame alone) is generated faster than it plays (3.7 s for 4.25 s on a 5090)
JOIN_FADE_FRAMES = 16  # frames of a continuing segment whose colors are brought to the frame it continues (match_join)
TAIL_FRAMES = 4  # the frames after a segment's anchor (its [1, 4] tail clip): regenerated by the next segment
STEPS = 2
WORLD_CONTROLS = ("walk", "look", "jump", "sprint", "crouch", "event")  # the shared explorer controls of a camera (W A S D, arrows, Space,
# Shift, C, typed events): a move's camera sentence (CAMERA) follows the keys held together
HISTORY_CLIPS = (0, 1, 2)  # the Memory menu: VAE clips of the previous segment the next one sees, besides its anchor frame
DEFAULT_HISTORY_CLIPS = 0  # the anchor frame alone: the history clips cost 0.4 s per clip (encode and attention), slower than playback


def segment_frames(history_clips, continued=True):
    """(history, generated, anchor) frames of a segment: the previous segment's frames it sees before its first frame, the frames it
    generates (its first one is the anchor, already shown, when it continues), the index of its own anchor (the next segment's first frame)."""
    history = CLIP_FRAMES * history_clips if continued else 0
    generated = WINDOW_FRAMES - history
    return history, generated, generated - TAIL_FRAMES - 1


def new_frames(history_clips):
    """Frames a continuing segment adds to the world: 102 without history clip (4.25 s), 85 with one, 68 with two."""
    return segment_frames(history_clips)[2]


MOVE_SECONDS = round(new_frames(DEFAULT_HISTORY_CLIPS) / FPS, 2)  # a move of the explorer: one segment
MAX_EXPLORED_FRAMES = 180 * FPS  # moves kept in RAM for Replay / Record: the last 3 minutes
FORMAT, VERSION, EXTENSION = "wgpworld", 1, ".wgpworld"
# the camera of a move as H3 prompts describe camera motion (type, amplitude, speed), per explorer key name (shared.utils.world_instructions):
# the keys held together make one sentence; Shift turns walking into running
CAMERA = {"w": "dollies forward about five meters at a steady walking pace", "s": "dollies backward about five meters at a steady walking pace",
          "a": "trucks left about three meters", "d": "trucks right about three meters",
          "left": "pans left about forty-five degrees", "right": "pans right about forty-five degrees",
          "up": "tilts up about thirty degrees", "down": "tilts down about thirty degrees",
          "jump": "rises in a short hop of about half a meter before landing back at eye level", "crouch": "lowers smoothly to crouching height, about one meter above the ground"}
RUNNING = {"w": "rushes forward about twelve meters at a running pace", "s": "rushes backward about twelve meters at a running pace", "sprint": "rushes forward about twelve meters at a running pace"}
STILL = "holds still at eye level"
# the moves whose prompts an exploration encodes at its start (about 1 s each, before the viewer can move): the walk, turning and a still
# camera; any other move waits ~4 s for the text encoder the first time it is used
PREPARED_MOVES = [["w"], ["s"], ["a"], ["d"], ["left"], ["right"], []]
DEFAULT_SOUNDSCAPE = "The natural ambient sound of the place, with soft footsteps that follow the camera's movement."
_FIELDS = ("integrated_multimodal_description:", "overall_soundscape:", "non_diegetic_music:")


def camera_sentence(keys):
    """The H3 sentence of a move: one continuous first-person take with the camera motion of the keys held together (none: a still camera)."""
    keys = set(keys)
    motions = [(RUNNING if "sprint" in keys else CAMERA)[key] for key in ("w", "s") if key in keys]
    if "sprint" in keys and not motions:
        motions.append(RUNNING["sprint"])
    motions += [CAMERA[key] for key in ("a", "d", "left", "right", "up", "down", "jump", "crouch") if key in keys]
    motions = motions or [STILL]
    joined = motions[0] if len(motions) == 1 else ", ".join(motions[:-1]) + " and " + motions[-1]
    return f"In one continuous first-person take without cuts, the camera {joined}."


def _fields(description):
    """The three fields of an H3 prompt in a world description: a structured one keeps its fields, plain text becomes the description field
    (with the soundscape of a walk and no score)."""
    fields, current = {}, None
    for line in description.strip().splitlines():
        name = next((field for field in _FIELDS if line.lstrip().lower().startswith(field)), None)
        if name is not None:
            current, line = name, line.lstrip()[len(name):]
        fields.setdefault(current or _FIELDS[0], []).append(line.strip())
    text = {name: " ".join(part for part in parts if part) for name, parts in fields.items()}
    visual = text.get(_FIELDS[0], "")
    if not visual.startswith("[Shot 1]"):
        visual = "[Shot 1] " + visual
    return visual, text.get(_FIELDS[1]) or DEFAULT_SOUNDSCAPE, text.get(_FIELDS[2]) or "N/A"


def segment_prompt(description, keys, event):
    """The H3 prompt of a segment: its three fields, the move's camera sentence (keys: explorer key names, None for no camera sentence) and
    its event appended to the description field."""
    visual, soundscape, music = _fields(description)
    parts = [visual] + ([] if keys is None else [camera_sentence(keys)]) + ([f"Meanwhile, {event.strip().rstrip('.')}."] if event else [])
    return "\n".join([f"{_FIELDS[0]} {' '.join(parts)}", f"{_FIELDS[1]} {soundscape}", f"{_FIELDS[2]} {music}"])


def explorer_menus(manifest):
    """The explorer's controls and menus for a pi-H3 world (handler query_world_explorer): the four moves and typed events, one segment
    per move, its 2 steps, and as Memory the video of the previous segment the next one sees. Keys pressed during a move are queued."""
    return {"controls": WORLD_CONTROLS, "queue_moves": True,
            "seconds": [(MOVE_SECONDS, f"{round(MOVE_SECONDS)} s", new_frames(DEFAULT_HISTORY_CLIPS))],
            "steps": [(STEPS, "2 Steps")],
            "memory": [(CLIP_FRAMES * clips, f"{(CLIP_FRAMES * clips + 1) / FPS:.2g}", ("last frame, faster than playback", "shorter moves, slower than playback",
                                                                                             "shorter moves, slowest")[clips]) for clips in HISTORY_CLIPS],
            "memory_title": "How much of the previous move each move sees: its last frame (the walk keeps up with playback), or also its last 0.7 or 1.4 s for "
                            "steadier motion, with shorter and slower moves (pauses between them)",
            "defaults": {"seconds": MOVE_SECONDS, "steps": STEPS, "memory": CLIP_FRAMES * manifest.get("history_clips", DEFAULT_HISTORY_CLIPS)},
            "task": {"num_inference_steps": STEPS, "video_length": WINDOW_FRAMES, "image_prompt_type": "T"}}


def match_join(video, shown, fade=JOIN_FADE_FRAMES):
    """Brings the first frames of a continuing segment (video: uint8 (3, frames, H, W), its frame 0 the regenerated anchor, not shown) to the
    colors of the anchor frame the previous segment showed (shown: (H, W, 3) uint8), in place: a continuation comes out darker and a little
    more contrasted than the frame it continues (the round trip DWD frame -> VAE encoder -> DWD head: 3 to 4 levels at its first shown
    frame, 5 to 6 at the regenerated anchor, whose single-frame latent the head projects on its own) and recovers over 8 to 16 frames, a
    dark blink at each join. The per-channel gain and offset that give its first shown frame the statistics of the shown anchor (the next
    frame of the video: nearly the same picture) apply in full to that frame, then fade out over `fade` frames."""
    regenerated = video[:, 1].flatten(1).float()
    target = torch.from_numpy(shown).permute(2, 0, 1).flatten(1).float()
    gain = (target.std(1) / regenerated.std(1).clamp_min(1.0)).view(3, 1, 1)
    offset = (target.mean(1) - gain.flatten() * regenerated.mean(1)).view(3, 1, 1)
    for index in range(1, min(fade + 1, video.shape[1])):
        weight = 0.5 * (1 + math.cos(math.pi * (index - 1) / fade))
        frame = video[:, index].float()
        video[:, index] = frame.add_(frame * (gain - 1) + offset, alpha=weight).round_().clamp_(0, 255).to(torch.uint8)


def _jpeg(frame, size=None, quality=None):
    image = Image.fromarray(np.ascontiguousarray(frame))
    if size is not None:
        image.thumbnail((size, size))
    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=quality or (85 if size else 92))
    return buffer.getvalue()


@dataclass
class WorldSession:
    """An open world: its manifest, the last segment's latents (its latent_slice: what the next segment continues from, one segment of
    CPU tensors), its last shown frame (H, W, 3 uint8) and, while exploring, the moves' frames."""
    manifest: dict
    overlap: dict | None = None
    last_frame: np.ndarray | None = None
    moves: int = 0
    world_frames: int = 0  # frames of the world's own video (its segments before this exploration)
    explored: list = field(default_factory=list)
    explored_frames: int = 0
    dropped_frames: int = 0

    def keep_move(self, frames):
        self.explored.append(frames)
        self.explored_frames += len(frames)
        while self.explored_frames - len(self.explored[0]) >= MAX_EXPLORED_FRAMES:
            self.explored_frames -= len(self.explored[0])
            self.dropped_frames += len(self.explored.pop(0))


class H3World:
    def __init__(self, pipeline, model_type):
        self.pipeline, self.model_type = pipeline, model_type
        self.settings = None  # the generation settings of the last queued task (an exploration outside the queue reuses them)

    # ---- segments

    def _prompt(self, prompt, image=None):
        """Encodes a prompt ahead of the denoising, without picture (a segment that continues another one shows none to the encoder),
        once: later uses read the TextEncoderCache. Returns whether it was cached."""
        pipeline = self.pipeline
        cached = pipeline._prompt_cache_key(prompt, []) in pipeline.text_encoder_cache
        if not cached:
            pipeline._encode_prompt(prompt, [])
        return cached

    def _segment(self, session, prompt, seed, callback, settings, history_clips, image_start=None, decode_audio=True):
        """Generates the next segment of the world: (shown frames (frames, H, W, 3) uint8, their sound (samples, 2) or None); the segment's
        latents become session.overlap."""
        manifest, previous = session.manifest, session.overlap
        history, generated, anchor = segment_frames(history_clips, previous is not None)
        start = previous["start_frame"] + previous["anchor"] - history if previous is not None else 0  # the window's first frame
        result = self.pipeline.generate(input_prompt=prompt, image_start=image_start if previous is None else None, prefix_frames_count=history + 1 if previous is not None else 0,
                                        overlapped_latents=previous, window_start_frame_no=start, frame_num=WINDOW_FRAMES, height=manifest["height"],
                                        width=manifest["width"], seed=seed, callback=callback, fps=FPS, sample_solver="euler", guide_phases=1, world_segment=True,
                                        decode_audio=decode_audio, **settings)
        if result is None:  # aborted
            raise GenerationAbortedHere()
        session.overlap = {**result["latent_slice"], "anchor": anchor}
        first = 0 if previous is None else 1  # a continuing segment's first frame is the anchor, already shown
        if previous is not None:
            match_join(result["x"], session.last_frame)
        frames = result["x"][:, first:anchor + 1].permute(1, 2, 3, 0).numpy()
        session.last_frame = frames[-1]
        audio = result.get("audio")
        if audio is not None:
            rate = result["audio_sampling_rate"]
            audio = audio[round(first * rate / FPS):round((anchor + 1) * rate / FPS)]
        manifest["frames"] = manifest.get("frames", 0) + len(frames)
        return frames, audio

    def _segment_callback(self, callback, index, total):
        """The pipeline's progress of segment index, as steps of the whole world (one 0 / N at the start)."""
        if callback is None:
            return None

        def wrapped(step, latents, force_refresh, **kwargs):
            if step < 0:
                if index == 0:
                    callback(-1, latents, force_refresh, **{**kwargs, "override_num_inference_steps": total * STEPS})
                return
            callback(index * STEPS + step, latents, force_refresh, **{key: value for key, value in kwargs.items() if key != "pass_no"})
        return wrapped

    # ---- worlds

    def _new_session(self, seed, height, width, description, history_clips):
        manifest = {"model_type": self.model_type, "width": width, "height": height, "fps": FPS, "steps": STEPS, "seed": seed, "world_id": uuid.uuid4().hex,
                    "world": {"description": description, "segments": []}, "segments": [], "history_clips": history_clips}
        return WorldSession(manifest)

    def open_world(self, path):
        with zipfile.ZipFile(path) as archive:
            manifest = json.loads(archive.read("manifest.json"))
            if manifest.get("format") != FORMAT or manifest.get("version") != VERSION:
                raise ValueError(f"{path} is not a version {VERSION} world file")
            tensors = load(archive.read("tensors.safetensors"))
            last_frame = np.array(Image.open(io.BytesIO(archive.read("poster.jpg"))).convert("RGB"))
            frames = [np.array(Image.open(io.BytesIO(archive.read(name))).convert("RGB")) for name in sorted(n for n in archive.namelist() if n.startswith("overlap/"))]
        overlap = {**manifest["overlap"], "video": tensors.get("video"), "audio": tensors["audio"]}
        if frames:
            overlap["frames"] = torch.from_numpy(np.stack(frames)).permute(3, 0, 1, 2)
        return WorldSession(manifest, overlap, last_frame, world_frames=manifest["frames"])

    def world_file(self, session):
        """The world's .wgpworld: manifest, the last segment's audio latents and what its continuation reads of its video (its latents, or
        with recycle_latents "frames" the frames of the longest overlap, JPEG), thumbnail and poster (its last frame)."""
        overlap = session.overlap
        frames, frames_start, anchor = overlap.get("frames"), overlap.get("frames_start", 0), overlap["anchor"]
        kept = max(frames_start, anchor - CLIP_FRAMES * HISTORY_CLIPS[-1])  # the first frame the longest overlap reads
        manifest = {"format": FORMAT, "version": VERSION, **session.manifest,
                    "overlap": {"start_frame": overlap["start_frame"], "audio_time_offset": float(overlap["audio_time_offset"]), "anchor": anchor,
                                **({"frames_start": kept} if frames is not None else {})}}
        tensors = {"audio": overlap["audio"].float().contiguous(), **({"video": overlap["video"].float().contiguous()} if overlap["video"] is not None else {})}
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_STORED) as archive:
            archive.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=1))
            archive.writestr("tensors.safetensors", save(tensors))
            if frames is not None:
                for index in range(kept, anchor + 1):
                    archive.writestr(f"overlap/{index:03d}.jpg", _jpeg(frames[:, index - frames_start].permute(1, 2, 0).numpy(), quality=95))
            archive.writestr("thumbnail.jpg", _jpeg(session.last_frame, 320))
            archive.writestr("poster.jpg", _jpeg(session.last_frame))
        return buffer.getvalue()

    def _add_segment(self, session, frames, keys, event, text, description):
        session.manifest["segments"].append({"video_frames": frames, "keys": "+".join(sorted(keys or ())), "event": event, **({"instruction": text} if text else {})})
        session.manifest["world"]["segments"].append({"visual_description_long": description if not session.manifest["world"]["segments"] else "",
                                                      "description_change": event or None, "instruction": text})

    def generate(self, input_prompt, input_custom, world_output, image_start, frame_num, height, width, seed, callback, settings):
        if input_custom is not None and input_prompt.strip() == EXPLORE_PROMPT:
            exploration = exploration_for(input_custom)
            return None if exploration is None else self._explore(exploration, callback, settings)
        self.settings = settings
        session = self.open_world(input_custom) if input_custom is not None else None
        description, instructions = split_instructions(input_prompt, WORLD_CONTROLS)
        if session is None:
            session = self._new_session(seed, height, width, description, DEFAULT_HISTORY_CLIPS)
        description = description or session.manifest["world"]["description"]
        moves = [(instruction["keys"], instruction["event"], max(1, round((instruction["seconds"] or MOVE_SECONDS) / MOVE_SECONDS)), instruction["text"]) for instruction in instructions]
        if not moves:  # no instructions: the description alone, for the requested length
            moves = [(None, "", max(1, round((int(frame_num) - 1) / new_frames(session.manifest["history_clips"]))), "")]
        total = sum(count for _, _, count, _ in moves)
        prompts = [segment_prompt(description, keys, event) for keys, event, _, _ in moves]
        set_phase_status("Encoding World Prompts")
        for index, prompt in enumerate(dict.fromkeys(prompts)):  # every prompt encoded once, before the denoising steps are announced
            if index or image_start is None or session.overlap is not None:  # the first segment of a world from an image shows it to the encoder
                self._prompt(prompt)
        video, sound, done = [], [], 0
        try:
            for (keys, event, count, text), prompt in zip(moves, prompts):
                shown = 0
                for _ in range(count):
                    set_phase_status(f"Generating World Segment {done + 1}/{total}")
                    frames, audio = self._segment(session, prompt, seed + session.manifest.get("frames", 0), self._segment_callback(callback, done, total), settings,
                                                  session.manifest["history_clips"], image_start)
                    video.append(frames)
                    sound.append(audio)
                    shown, done = shown + len(frames), done + 1
                    check_abort()
                self._add_segment(session, shown, keys, event, text, description)
        except GenerationAbortedHere:
            return None
        samples = {"x": torch.from_numpy(np.concatenate(video)).permute(3, 0, 1, 2), "audio": np.concatenate(sound), "audio_sampling_rate": self.pipeline_rate()}
        if (world_output or "world") != "video":
            samples["side_files"] = {EXTENSION: self.world_file(session)}
        return samples

    @staticmethod
    def pipeline_rate():
        from .pipeline import AUDIO_SAMPLE_RATE
        return AUDIO_SAMPLE_RATE

    # ---- exploration

    def explore(self, world_path):
        """Serves the exploration of a world outside the queue (the Worlds gallery took the GPU from a running generation)."""
        if self.settings is None:
            raise ValueError("Explore a pi-H3 world from the queue first: no generation of this model has run since it was loaded")
        exploration = exploration_for(world_path)
        if exploration is not None:
            self._explore(exploration, None, self.settings)

    def _render(self, session, world_path):
        """The world's own video (its .mp4, when it was saved) then the moves kept in RAM (uint8, frames x H x W x 3)."""
        import os
        import imageio.v3 as iio
        from shared.utils.world_outputs import video_path
        parts = [iio.imread(video_path(world_path))[..., :3]] if os.path.isfile(video_path(world_path)) else []
        return np.concatenate(parts + session.explored) if parts or session.explored else session.last_frame[None]

    def _move_stats(self, session, seconds, frames):
        from shared.utils.stats import live_stats

        def amount(video_frames):
            return {"seconds": round(video_frames / FPS, 1), "frames": video_frames, "moves": round(video_frames / new_frames(session.manifest["history_clips"]))}

        world = session.world_frames
        explored = session.manifest["frames"]
        history = CLIP_FRAMES * session.manifest["history_clips"] + 1
        memory = (f"Memory   each move continues from the last {history / FPS:.1f} s ({history} frames) of the previous one"
                  + (f" · Replay keeps the last {MAX_EXPLORED_FRAMES // FPS} s of moves" if session.dropped_frames else ""))
        return {"move_seconds": round(seconds, 2), "video_seconds": round(frames / FPS, 2), "steps": STEPS, "moves": session.moves,
                "peak_gb": round(torch.cuda.max_memory_allocated(self.pipeline.device) / 2**30, 1), **live_stats(), "world": amount(world),
                "explored_moves": amount(explored - world), "explored": amount(explored), "memory": amount(history), "memory_full": False, "room_moves": 0, "memory_line": memory}

    def _explore(self, exploration, callback, settings):
        """Serves the moves of an exploration until the viewer leaves (or the task is aborted); nothing is saved unless asked."""
        try:
            set_phase_status("Preparing World")
            session = self.open_world(exploration.world_path)
            description = session.manifest["world"]["description"]
            for keys in PREPARED_MOVES:  # encoded once, now, in one text encoder load: their moves then only read the cache
                self._prompt(segment_prompt(description, keys, ""))
            exploration.publish("ready")
            finished = None  # when the last move was generated
            while True:
                set_phase_status("Exploring World - Waiting for a Move")
                try:
                    request = exploration.next_request(0.25)
                except queue.Empty:
                    check_abort()
                    continue
                if request is None:
                    break
                if "render" in request:
                    set_phase_status("Exploring World - Rendering the Video")
                    exploration.publish("rendered", frames=self._render(session, exploration.world_path), fps=FPS, record=request["render"], moves=session.moves)
                    continue
                if "save" in request:
                    set_phase_status("Exploring World - Saving the World")
                    exploration.publish("saved", data=self.world_file(session), moves=session.moves)
                    continue
                set_phase_status(f"Exploring World - Move {session.moves + 1}")
                keys, event = (request["keys"] or {}).get("keys", ""), request["text"]
                keys = [key for key in keys.split("+") if key]
                if request.get("memory") is not None:
                    session.manifest["history_clips"] = max(0, min(HISTORY_CLIPS[-1], round(request["memory"] / CLIP_FRAMES)))
                prompt = segment_prompt(description, keys, event)
                cached = self._prompt(prompt)
                started = time.perf_counter()
                if settings["verbose_level"] >= 1:
                    waited = "" if finished is None else f", {started - finished:.2f} s after the previous move"
                    tqdm.write(f"World move {session.moves + 1} [{'+'.join(keys) or 'still'}{' / ' + event if event else ''}]: prompt encoding {'reused' if cached else 'computed'}{waited}")
                torch.cuda.reset_peak_memory_stats(self.pipeline.device)
                frames, _ = self._segment(session, prompt, session.manifest["seed"] + session.manifest["frames"], callback, settings, session.manifest["history_clips"],
                                          decode_audio=False)  # the explorer's clips are silent
                session.moves += 1
                self._add_segment(session, len(frames), keys, event, "", description)
                session.keep_move(frames)
                finished = time.perf_counter()
                exploration.publish("clip", frames=frames, fps=FPS, stats=self._move_stats(session, finished - started, len(frames)), seq=request.get("seq"))
        except GenerationAbortedHere:
            pass
        finally:
            exploration.publish("ended")
        return None


class GenerationAbortedHere(Exception):
    """A segment's generation returned nothing: the task was aborted."""


